int key_expansion(int key[4][4], int s_box[256], int expanded[44][4], int i, int j)
{
    int rc[10] = {0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36};
    if (i < 4)
    {
        return key[i][j];
    }
    else if (i % 4 == 0)
    {
        if (j == 0)
        {
            return expanded[i-4][0] ^ rc[(i/4) - 1] ^ s_box[expanded[i-1][1]];
        }
        else
        {
            return expanded[i-4][j] ^ s_box[expanded[i-1][(j+1) % 4]];
        }
    }
    else
    {
        return expanded[i-4][j] ^ expanded[i-1][j];
    }
}
int add_round_key(int state[4][4], int expanded[44][4], int i, int j, int round)
{
    return state[i][j] ^ expanded[(4*round) + i][j];
}

int sub_bytes(int state[4][4], int s_box[256], int i, int j)
{
    int temp = s_box[state[i][j]];
    return state[i][j] ^ temp;
}
int shift_rows(int state[4][4], int i, int j)
{
    return state[i][(j+i)%4];
}
int mix_columns(int state[4][4], int i, int j)
{
    int arr[4] = {2, 3, 1, 1};
    int t = 0;
    for (int a = 0 ; a < 4 ; a++)
    {
        t += arr[(a-i)%4]*state[a][j];
    }
    return t % 256;
}

